#!/usr/bin/env python3
"""Write CATALOGUE.md: every policy card and news event, straight from config/.

POLICIES.md and EVENTS.md are design notes written as the first cards and
events went in, and their counts went stale as the game grew. This listing is
generated, so it cannot drift. Run it after editing config/policies.json or
config/events.json:

    python3 scripts/catalogue.py > CATALOGUE.md
"""
import json, os

ROOT = os.path.join(os.path.dirname(__file__), '..')
pol = json.load(open(os.path.join(ROOT, 'config', 'policies.json')))['policies']
ev = json.load(open(os.path.join(ROOT, 'config', 'events.json')))
ev = ev if isinstance(ev, list) else ev['events']


def quarter(q):
    """Quarter index (0 = 2026 Q2) as the game labels it."""
    return f"{2026 + (q + 1) // 4} Q{(q + 1) % 4 + 1}"


def cell(s):
    return str(s).replace('|', '/').replace('\n', ' ')


def card_when(c):
    bits = []
    if c.get('scriptedQuarter') is not None:
        bits.append('from ' + quarter(c['scriptedQuarter']))
    if c.get('requires'):
        r = c['requires']
        bits.append('needs ' + (', '.join(r) if isinstance(r, list) else json.dumps(r)))
    if c.get('proposal'):
        bits.append(f"proposed by {c['proposal'].get('party', '?')}")
    return '; '.join(bits) or 'from the start'


def event_when(e):
    t = e.get('trigger') or {}
    kind = t.get('type')
    if e.get('scriptedQuarter') is not None:
        return 'scripted, ' + quarter(e['scriptedQuarter'])
    if kind == 'afterOption':
        lag = t.get('inQuarters')
        return f"after `{t.get('card')}` → `{t.get('option')}`" + (f", +{lag}q" if lag else '')
    if kind == 'flag':
        f = t.get('flag') or t.get('flags')
        return 'when flag ' + (', '.join(f'`{x}`' for x in f) if isinstance(f, list) else f'`{f}`') + ' is set'
    if kind == 'threshold':
        return 'threshold: ' + ', '.join(f'{k} {v}' for k, v in t.items() if k != 'type')
    if kind == 'hazard':
        return 'random: ' + ', '.join(f'{k} {v}' for k, v in t.items() if k != 'type')
    return kind or '—'


n_opt = sum(len(c['options']) for c in pol)
e_opt = sum(len(e['options']) for e in ev)
print('# Catalogue\n')
print('Generated by `scripts/catalogue.py` from `config/`. Do not edit by hand.\n')
print(f'**{len(pol)} policy cards, {n_opt} options. {len(ev)} news events, {e_opt} options.**\n')

print('## Policy cards\n')
ministries = []
for c in pol:
    if c['ministry'] not in ministries:
        ministries.append(c['ministry'])
for m in ministries:
    title = ' '.join(w.upper() if w in ('pm', 'eec') else w.capitalize() for w in m.split())
    print(f'### {title}\n')
    print('| Card | Options | Available |')
    print('|---|---|---|')
    for c in (c for c in pol if c['ministry'] == m):
        opts = ' · '.join(cell(o['label']) + (' *(unselectable)*' if o.get('unavailable') else '')
                          for o in c['options'])
        print(f"| **{cell(c['name'])}** `{c['id']}` | {opts} | {cell(card_when(c))} |")
    print()

print('## News events\n')
print('| Event | Options | Fires | |')
print('|---|---|---|---|')
for e in ev:
    opts = ' · '.join(cell(o['label']) + (' *(unselectable)*' if o.get('unavailable') else '')
                      for o in e['options'])
    tags = ', '.join(t for t, on in (('blocking', e.get('blocking')), ('costs an action', e.get('costsAction'))) if on)
    print(f"| **{cell(e['headline'])}** `{e['id']}` | {opts} | {cell(event_when(e))} | {tags} |")
